/* sha256_gen.cpp — known-answer vectors for formal/spark/tests/test_sha256.adb,
 * produced by the C++ engine's own SHA-256 (src/sha256.cpp).
 *
 * Build (repo root):
 *   c++ -std=c++17 -I include -I src formal/spark/vectors/gen/sha256_gen.cpp \
 *       build/libsync_engine.a build/libmonocypher.a -lpthread -o /tmp/sha256_gen
 *   /tmp/sha256_gen > formal/spark/vectors/sha256.txt
 *
 * Line formats (hex fields separated by spaces; "-" is the empty hex string):
 *   kat    <msg>  <digest>                   one-shot sha256(msg)
 *   repeat <byte> <count>  <digest>          one-shot over `count` copies of byte
 *   split  <msg>  <sizes>  <digest>          Sha256::update once per chunk, then
 *                                            finish; <sizes> is 2 bytes big-endian
 *                                            per chunk and the sizes sum to |msg|
 * The NIST FIPS 180-4 answers are asserted here so the file is anchored to the
 * standard, not just to the C++. */
#include <cstdio>
#include <cstdint>
#include <cstdlib>
#include <cstring>
#include <string>
#include <vector>

#include "sha256.h"

using sync_engine_detail::Sha256;
using sync_engine_detail::sha256;

static std::string hex(const uint8_t *p, size_t n) {
    static const char *d = "0123456789abcdef";
    std::string s;
    if (n == 0) return "-";
    s.reserve(2 * n);
    for (size_t i = 0; i < n; i++) { s += d[p[i] >> 4]; s += d[p[i] & 15]; }
    return s;
}

static std::string hex(const std::vector<uint8_t> &v) { return hex(v.data(), v.size()); }

/* Deterministic byte source (xorshift64*), so the file is reproducible. */
static uint64_t rng_state = 0x9E3779B97F4A7C15ull;
static uint32_t rnd() {
    rng_state ^= rng_state >> 12;
    rng_state ^= rng_state << 25;
    rng_state ^= rng_state >> 27;
    return (uint32_t)((rng_state * 2685821657736338717ull) >> 32);
}

static std::vector<uint8_t> rand_bytes(size_t n) {
    std::vector<uint8_t> v(n);
    for (size_t i = 0; i < n; i++) v[i] = (uint8_t)rnd();
    return v;
}

static void kat(const std::vector<uint8_t> &msg, const char *expect) {
    uint8_t d[32];
    sha256(msg.data(), msg.size(), d);
    std::string got = hex(d, 32);
    if (expect && got != expect) {
        std::fprintf(stderr, "NIST mismatch: got %s want %s\n", got.c_str(), expect);
        std::exit(1);
    }
    std::printf("kat %s %s\n", hex(msg).c_str(), got.c_str());
}

static void repeat(uint8_t b, uint64_t count, const char *expect) {
    Sha256 h;
    std::vector<uint8_t> chunk(4096, b);
    uint64_t left = count;
    while (left > 0) {
        size_t take = left < chunk.size() ? (size_t)left : chunk.size();
        h.update(chunk.data(), take);
        left -= take;
    }
    uint8_t d[32];
    h.finish(d);
    std::string got = hex(d, 32);
    if (expect && got != expect) {
        std::fprintf(stderr, "NIST mismatch (repeat): got %s want %s\n", got.c_str(), expect);
        std::exit(1);
    }
    uint8_t cnt[8];
    for (int i = 0; i < 8; i++) cnt[i] = (uint8_t)(count >> (56 - 8 * i));
    std::printf("repeat %s %s %s\n", hex(&b, 1).c_str(), hex(cnt, 8).c_str(), got.c_str());
}

static void split(const std::vector<uint8_t> &msg, const std::vector<size_t> &sizes) {
    Sha256 h;
    size_t off = 0;
    std::vector<uint8_t> enc;
    for (size_t s : sizes) {
        if (off + s > msg.size()) { std::fprintf(stderr, "bad split\n"); std::exit(1); }
        h.update(msg.data() + off, s);
        off += s;
        enc.push_back((uint8_t)(s >> 8));
        enc.push_back((uint8_t)s);
    }
    if (off != msg.size()) { std::fprintf(stderr, "split does not cover\n"); std::exit(1); }
    uint8_t d[32];
    h.finish(d);
    /* Cross-check against the one-shot: the generator itself must agree. */
    uint8_t d2[32];
    sha256(msg.data(), msg.size(), d2);
    if (std::memcmp(d, d2, 32) != 0) { std::fprintf(stderr, "split != one-shot\n"); std::exit(1); }
    std::printf("split %s %s %s\n", hex(msg).c_str(), hex(enc).c_str(), hex(d, 32).c_str());
}

int main() {
    std::printf("# SHA-256 vectors generated by formal/spark/vectors/gen/sha256_gen.cpp\n");
    std::printf("# from src/sha256.cpp. See the generator for the line formats.\n");

    /* NIST FIPS 180-4 / CAVP known answers. */
    std::printf("# NIST known answers\n");
    kat({}, "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855");
    kat({'a', 'b', 'c'}, "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad");
    {
        const char *m = "abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq";
        kat(std::vector<uint8_t>(m, m + std::strlen(m)),
            "248d6a61d20638b8e5c026930c3e6039a33ce45964ff2167f6ecedd419db06c1");
    }
    {
        const char *m = "abcdefghbcdefghicdefghijdefghijkefghijklfghijklmghijklmnhijklmno"
                        "ijklmnopjklmnopqklmnopqrlmnopqrsmnopqrstnopqrstu";
        kat(std::vector<uint8_t>(m, m + std::strlen(m)),
            "cf5b16a778af8380036ce59e7b0492370b249b11e8f07a51afac45037afee9d1");
    }
    repeat('a', 1000000, "cdc76e5c9914fb9281a1c7e284d73e67f1809a48a497200e046d39ccc7112cd0");
    /* Single-byte and four-byte CAVP ShortMsg answers (not ASCII, so a
     * text-oriented bug would show). */
    kat({0xbd}, "68325720aabd7c82f30f554b313d0570c95accbb7dc4b5aae11204c08ffe732b");
    kat({0xc9, 0x8c, 0x8e, 0x55},
        "7abc22c0ae5af26ce93dbb94433a0e0b2e119d014f8e7f65bd56c61ccccd9504");
    /* NIST "abc" as update("ab"), update("c"): the gtest one-shot through the
     * incremental path. */
    split({'a', 'b', 'c'}, {2, 1});

    /* Repeat counts at every padding boundary, at the point where the bit
     * length needs a second, third and fifth byte (2**5, 2**13, 2**29 bytes),
     * and a few prime-ish counts. The Ada side feeds these through Update
     * with rotating chunk sizes, so they also exercise Absorb's buffer
     * handling at large totals. */
    std::printf("# repeat, padding boundaries and bit-length byte widths\n");
    for (uint64_t n : {0ull, 1ull, 31ull, 32ull, 33ull, 55ull, 56ull, 57ull, 63ull, 64ull,
                       65ull, 119ull, 120ull, 127ull, 128ull, 129ull, 8191ull, 8192ull,
                       8193ull, 65535ull, 65536ull, 65537ull, 1000003ull, 2097151ull,
                       2097152ull})
        repeat((uint8_t)(0xa5 + n), n, nullptr);
    repeat(0x5c, (1ull << 29) + 7, nullptr);   /* bits = 2**32 + 56 */

    /* Every length 0 .. 200 (covers all padding boundaries twice over), plus a
     * few that cross multiple blocks. */
    std::printf("# one-shot, lengths 0..200 and block multiples\n");
    for (size_t n = 0; n <= 200; n++) kat(rand_bytes(n), nullptr);
    for (size_t n : {255, 256, 257, 511, 512, 513, 1000, 1023, 1024, 1025, 1500})
        kat(rand_bytes(n), nullptr);

    /* Incremental splits: fixed chunk sizes 1..200 over a 600-byte message. */
    std::printf("# incremental, fixed chunk size 1..200\n");
    {
        std::vector<uint8_t> msg = rand_bytes(600);
        for (size_t c = 1; c <= 200; c++) {
            std::vector<size_t> sizes;
            size_t off = 0;
            while (off < msg.size()) {
                size_t s = std::min(c, msg.size() - off);
                sizes.push_back(s);
                off += s;
            }
            split(msg, sizes);
        }
    }

    /* Incremental splits: random chunk sizes in 1..200, including zero-length
     * updates, over random message lengths. */
    std::printf("# incremental, random chunk sizes 1..200 (with some empty updates)\n");
    for (int t = 0; t < 120; t++) {
        size_t n = rnd() % 1500;
        std::vector<uint8_t> msg = rand_bytes(n);
        std::vector<size_t> sizes;
        size_t off = 0;
        while (off < n) {
            if (rnd() % 7 == 0) sizes.push_back(0);
            size_t s = 1 + rnd() % 200;
            if (s > n - off) s = n - off;
            sizes.push_back(s);
            off += s;
        }
        if (rnd() % 3 == 0) sizes.push_back(0);
        split(msg, sizes);
    }

    /* Large chunks: several blocks per update, chunk boundaries that are
     * block-aligned, off by one, and a single 8000-byte update. */
    std::printf("# incremental, large chunks\n");
    {
        std::vector<uint8_t> msg = rand_bytes(8000);
        split(msg, {8000});
        split(msg, {4096, 3904});
        split(msg, {4095, 3905});
        split(msg, {4097, 3903});
        split(msg, {1, 4096, 1, 3902});
        split(msg, {63, 4096, 65, 3776});
        split(msg, {2048, 2048, 2048, 1856});
        split(msg, {0, 8000, 0});
        std::vector<size_t> ones(8000, 1);
        split(msg, ones);
    }

    /* Only empty updates: must equal the empty-message answer. And an empty
     * update between every byte of "abc". */
    std::printf("# incremental, empty updates only\n");
    split({}, {0, 0, 0});
    split({'a', 'b', 'c'}, {0, 1, 0, 1, 0, 1, 0});

    /* Every (length, first chunk) pair around one block: catches an off-by-one
     * in the take computation at every fill level of the buffer. */
    std::printf("# incremental, every buffer fill level 0..63 then 1..130 bytes\n");
    for (size_t fill = 0; fill <= 63; fill++) {
        for (size_t second : {(size_t)1, 64 - fill, 65 - fill, 66 - fill, (size_t)130}) {
            if (second == 0) continue;
            std::vector<uint8_t> msg = rand_bytes(fill + second);
            split(msg, {fill, second});
        }
    }

    /* Boundary-hugging splits: chunks that land exactly on 55/56/63/64/65. */
    std::printf("# incremental, padding and block boundaries\n");
    for (size_t first : {55, 56, 57, 63, 64, 65, 119, 120, 127, 128, 129}) {
        std::vector<uint8_t> msg = rand_bytes(first + 200);
        split(msg, {first, 200});
        split(msg, {first, 1, 199});
        split(msg, {1, first - 1, 200});
    }
    return 0;
}
